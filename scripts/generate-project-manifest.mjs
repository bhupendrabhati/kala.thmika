#!/usr/bin/env node
/**
 * KALATHMIKA — Project Manifest Generator
 * ------------------------------------------------------------------
 * A browser cannot list directories, so the featured-project data layer
 * is generated from the real folders on disk.
 *
 * Source of truth (never renamed by this script):
 *   assets/images/project-images/<Category>/<Project-Folder>/<image files>
 *
 * Output (checked in, so the site also works with zero build step):
 *   assets/js/project-manifest.js  ->  window.KALATHMIKA_PROJECTS
 *
 * Usage:
 *   node scripts/generate-project-manifest.mjs
 *
 * Re-run it any time you add / remove / rename a project folder or an
 * image. The featured projects UI, project counts and galleries all read
 * from the manifest, so they update themselves automatically.
 *
 * Zero dependencies — plain Node.js.
 */

import { readdir, writeFile, mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = path.join(ROOT, 'assets', 'images', 'project-images');
const OUT_DIR = path.join(ROOT, 'assets', 'js');
const OUT_FILE = path.join(OUT_DIR, 'project-manifest.js');

const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif']);
const IGNORED_NAMES = new Set(['.ds_store', 'thumbs.db', '.gitkeep', 'desktop.ini']);

/** Human-friendly, number aware ordering: 2.jpg before 10.jpg, P-2 before P-10 */
const naturalCompare = (a, b) =>
    String(a).localeCompare(String(b), undefined, { numeric: true, sensitivity: 'base' });

const toUrlPath = (absolutePath) =>
    path
        .relative(ROOT, absolutePath)
        .split(path.sep)
        .map(encodeURI)
        .join('/');

const isImage = (name) => IMAGE_EXTENSIONS.has(path.extname(name).toLowerCase());
const isHidden = (name) => name.startsWith('.') || IGNORED_NAMES.has(name.toLowerCase());

/** Only directories, sorted naturally */
async function readDirectories(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    return entries
        .filter((entry) => entry.isDirectory() && !isHidden(entry.name))
        .map((entry) => entry.name)
        .sort(naturalCompare);
}

/** Only image files, sorted naturally */
async function readImages(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    return entries
        .filter((entry) => entry.isFile() && !isHidden(entry.name) && isImage(entry.name))
        .map((entry) => toUrlPath(path.join(directory, entry.name)))
        .sort((a, b) => naturalCompare(path.basename(a), path.basename(b)));
}

async function buildManifest() {
    const categories = [];

    for (const categoryFolder of await readDirectories(SOURCE_DIR)) {
        const categoryPath = path.join(SOURCE_DIR, categoryFolder);
        const projects = [];

        for (const projectFolder of await readDirectories(categoryPath)) {
            const images = await readImages(path.join(categoryPath, projectFolder));
            projects.push({ folder: projectFolder, images });
        }

        // A category with no project folders at all is still valid — it simply renders empty.
        categories.push({ folder: categoryFolder, projects });
    }

    return {
        version: 1,
        basePath: toUrlPath(SOURCE_DIR),
        categories
    };
}

function buildFile(manifest) {
    const categories = manifest.categories
        .map((category) => {
            const projects = category.projects
                .map(
                    (project) =>
                        `      { folder: ${JSON.stringify(project.folder)}, images: ${JSON.stringify(project.images)} }`
                )
                .join(',\n');
            return `    {\n      folder: ${JSON.stringify(category.folder)},\n      projects: [\n${projects}\n      ]\n    }`;
        })
        .join(',\n');

    return `/*!
 * KALATHMIKA — Featured Projects Manifest (auto-generated)
 * ------------------------------------------------------------------
 * DO NOT EDIT BY HAND.
 * Generated by scripts/generate-project-manifest.mjs from the real folders
 * inside ${manifest.basePath}/
 *
 * Regenerate after adding, removing or renaming any project folder or image:
 *   node scripts/generate-project-manifest.mjs
 *
 * This is a plain script (not JSON) on purpose so the manifest also loads
 * correctly when the site is opened directly from the file system.
 */
window.KALATHMIKA_PROJECTS = {
  version: ${manifest.version},
  basePath: ${JSON.stringify(manifest.basePath)},
  categories: [
${categories}
  ]
};
`;
}

async function main() {
    let manifest;

    try {
        manifest = await buildManifest();
    } catch (error) {
        console.error(`\n  Could not read ${toUrlPath(SOURCE_DIR)}/`);
        console.error(`  ${error.message}\n`);
        process.exitCode = 1;
        return;
    }

    const next = buildFile(manifest);

    let current = null;
    try {
        current = await readFile(OUT_FILE, 'utf8');
    } catch {
        /* first run */
    }

    if (current === next) {
        console.log('  Manifest already up to date — nothing written.');
    } else {
        await mkdir(OUT_DIR, { recursive: true });
        await writeFile(OUT_FILE, next, 'utf8');
        console.log(`  Wrote ${toUrlPath(OUT_FILE)}`);
    }

    const stats = manifest.categories.map((category) => {
        const images = category.projects.reduce((total, project) => total + project.images.length, 0);
        console.log(
            `    ${category.folder.padEnd(14)} ${String(category.projects.length).padStart(3)} projects  ${String(
                images
            ).padStart(4)} images`
        );
        return { projects: category.projects.length, images };
    });

    console.log(
        `    ${'TOTAL'.padEnd(14)} ${String(stats.reduce((t, s) => t + s.projects, 0)).padStart(3)} projects  ${String(
            stats.reduce((t, s) => t + s.images, 0)
        ).padStart(4)} images\n`
    );
}

main();
